#!/bin/sh
# Re-resolve requirements.in to exact versions in requirements.txt, for the image's
# Python (3.12, Linux x86_64), whatever Python runs this. Needs pip; no Docker.
# Rebuild and test after: nothing moves until this file changes and is committed.
set -e
cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
python3 -m pip install -q --dry-run --ignore-installed --target "$tmp/t" \
    --python-version 3.12 --only-binary=:all: \
    --platform manylinux_2_28_x86_64 --platform manylinux_2_17_x86_64 \
    --platform manylinux2014_x86_64 --platform linux_x86_64 \
    --report "$tmp/report.json" -r requirements.in
{
    echo "# Generated by ./lock.sh from requirements.in: every package, exact versions, resolved"
    echo "# for the image (Python 3.12, Linux x86_64). Don't edit by hand."
    python3 -c 'import json, sys
r = json.load(open(sys.argv[1]))
for m in sorted((i["metadata"] for i in r["install"]), key=lambda m: m["name"].lower()):
    print(m["name"].lower() + "==" + m["version"])' "$tmp/report.json"
} > requirements.txt
echo "requirements.txt: $(grep -vc '^#' requirements.txt) packages"
